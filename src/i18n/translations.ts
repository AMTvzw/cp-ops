export const interpolate = (template: string, vars?: Record<string, string | number>): string => {
  if (!vars) return template;
  return template.replace(/\{([^}]+)\}/g, (_, key: string) => {
    if (!(key in vars)) return `{${key}}`;
    return String(vars[key]);
  });
};
